-- ---------------------------------------------------------------------------
-- events
-- ---------------------------------------------------------------------------
-- A class, workshop or retreat. The central table: registrations, testimonials
-- and waiting-list entries all hang off it.
--
-- Bilingual columns follow the site-wide convention — `_ro` is required, `_en`
-- is optional and falls back to Romanian when blank.
--
-- `price` is a whole number in the major unit (150 means 150 RON, not 1.50).
-- Conversion to Stripe's minor units happens in one place, `lib/money.ts`.
--
-- `max_participants` NULL means unlimited. Zero and negative values are
-- rejected rather than treated as unlimited, because a capacity of zero is
-- indistinguishable from a full event and silently means nobody can book.
create table if not exists public.events (
  id                  uuid primary key default gen_random_uuid(),
  slug                text unique not null,
  title_ro            text not null,
  title_en            text,
  description_ro      text,
  description_en      text,
  date                date not null,
  time                time not null,
  location            text,
  price               integer not null default 0,
  currency            text not null default 'RON',
  max_participants    integer,
  image_url           text,
  whatsapp_group_link text,
  published           boolean default false,
  created_at          timestamptz default now(),
  updated_at          timestamptz default now()
);

-- The admin panel writes to PostgREST straight from the browser, so `min="0"`
-- on a form input is advice to the person typing, not a rule. These constraints
-- are the enforcement. A negative price would reach Stripe as a negative
-- charge; a non-positive capacity marks the whole calendar sold out.
alter table public.events drop constraint if exists events_price_non_negative;
alter table public.events add  constraint events_price_non_negative
  check (price >= 0);

alter table public.events drop constraint if exists events_capacity_positive;
alter table public.events add  constraint events_capacity_positive
  check (max_participants is null or max_participants > 0);

-- Four supported currencies, checked here because Stripe rejects an unknown
-- code at checkout — the worst possible moment to find out. Kept as a column
-- rather than a lookup table: four options that change roughly never.
alter table public.events drop constraint if exists events_currency_supported;
alter table public.events add  constraint events_currency_supported
  check (currency in ('RON', 'EUR', 'USD', 'GBP'));

alter table public.events enable row level security;

drop policy if exists "Anyone can view published events" on public.events;
create policy "Anyone can view published events"
  on public.events for select
  using (published = true);

drop policy if exists "Admins can manage events" on public.events;
create policy "Admins can manage events"
  on public.events for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());


