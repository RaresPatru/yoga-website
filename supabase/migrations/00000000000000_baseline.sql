-- ============================================================================
-- Baseline schema
-- ============================================================================
--
-- The complete current state of the database, in one file. Everything the
-- application depends on is created here: tables, the availability view, the
-- two functions, every RLS policy, every grant, indexes, storage
-- configuration, and the reference rows the admin panel expects to find.
--
-- HOW TO READ THIS FILE
--
-- Comments describe what each object is *for* and who is allowed to touch it.
-- They do not describe how it came to exist. Sixteen dated migrations, each
-- explaining the problem it solved, are kept verbatim in
-- `supabase/migrations-archive/` — that is where to look for the reasoning
-- behind a decision that looks strange.
--
-- WHAT THIS FILE IS NOT
--
-- It is not a change to production. Production already has this schema; this
-- is the file that lets `supabase db reset` rebuild it locally, and the one
-- place to read to find out what exists.
--
-- Every statement is idempotent — `if not exists`, `create or replace`, or a
-- `drop ... if exists` immediately before the create. Running it twice is a
-- no-op, which matters because an accidental run against a real database
-- should be boring.
--
-- ADDING SOMETHING NEW
--
-- Do not edit this file. Write a new dated migration, run it locally, then
-- apply it to production. See docs/DATABASE.md for the checklist — the step
-- people forget is the GRANT, and a missing grant has shipped a broken feature
-- here twice.
-- ============================================================================


-- ############################################################################
-- 1. ADMINISTRATORS
-- ############################################################################
--
-- First, because nearly every policy below calls is_admin(), and Postgres
-- resolves the function when the policy is created rather than when it runs.

-- ---------------------------------------------------------------------------
-- admins
-- ---------------------------------------------------------------------------
-- The list of people allowed into /admin. One row per account.
--
-- This exists because `auth.role() = 'authenticated'` — the obvious way to
-- write an admin policy in Supabase — means only "is logged in at all", not
-- "is an administrator". Every policy on this schema therefore tests
-- `is_admin()` instead.
--
-- Nothing reaches this table through the public API, not even a logged-in
-- user: it is read exclusively by is_admin(), which runs with elevated
-- privileges. Locking it down here means a user cannot inspect or modify the
-- admin list even if a policy elsewhere is written incorrectly.
--
-- `on delete cascade` means deleting the auth account removes the admin rights
-- with it.
create table if not exists public.admins (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  email      text,
  created_at timestamptz not null default now()
);

alter table public.admins enable row level security;
revoke all on public.admins from anon, authenticated;

-- Note: administrators are not seeded here. Locally, supabase/seed.sql creates
-- the Playwright test admin. In production the row already exists, and adding
-- one is a deliberate act performed by hand.


-- ---------------------------------------------------------------------------
-- is_admin()
-- ---------------------------------------------------------------------------
-- "Is the person making this request on the admins list?" Called by nearly
-- every RLS policy in this file.
--
--   security definer  Runs as its creator rather than the caller. Required,
--                     because `admins` is revoked from everyone above — without
--                     it the function could not read the table it depends on.
--                     Also prevents infinite recursion, where a policy calls a
--                     function that triggers the same policy.
--
--   set search_path   Pins the schemas this function searches. Without it,
--                     someone able to create objects could define their own
--                     `admins` table in a schema searched first and have this
--                     function — which runs with elevated privileges — read
--                     theirs instead. Supabase's linter flags every SECURITY
--                     DEFINER function that omits this.
--
--   stable            The answer cannot change within one query, so Postgres
--                     calls it once rather than once per row. A meaningful
--                     speedup when a policy runs over a whole table.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.admins where user_id = auth.uid()
  );
$$;

-- `revoke ... from public` first, and this is the important line. Postgres
-- grants EXECUTE to PUBLIC — the implicit group containing every role — when a
-- function is created, so revoking `anon` and `authenticated` by name leaves
-- them holding EXECUTE by inheritance. `pg_dump` does not print default PUBLIC
-- grants either, so the omission is invisible in a schema dump. That is how
-- register_for_event stayed callable by anyone for a month; see
-- migrations-archive/20260812000003_revoke_public_execute_on_functions.sql.
--
-- anon and authenticated genuinely need this one: RLS policy expressions are
-- evaluated with the caller's privileges, so any role reading a table with an
-- is_admin() policy must be able to execute it. It discloses nothing — it
-- answers only about the caller, and returns false for anyone anonymous.
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;


