-- ############################################################################
-- 5. CAPACITY: THE VIEW AND THE FUNCTION
-- ############################################################################
--
-- These two must agree. When the number a page displays and the rule the
-- booking button enforces disagree, you get the worst kind of bug: a page
-- offering seats next to a button that refuses them. The shared definition of
-- "does this registration hold a seat?" is:
--
--     not refunded, AND (not pending OR younger than pending_hold_interval)

-- ---------------------------------------------------------------------------
-- pending_hold_interval()
-- ---------------------------------------------------------------------------
-- How long an unpaid 'pending' registration may hold a seat.
--
-- Normally a seat comes back on its own: if the person never pays, Stripe fires
-- checkout.session.expired and the webhook deletes the row. But that only
-- happens if a Stripe session was ever created. Close the tab between
-- /api/register and /api/stripe/checkout and there is no session, so no expiry
-- event, so nothing ever releases the seat.
--
-- An hour, against Stripe sessions that expire in 30 minutes, leaves generous
-- room for the webhook to arrive first. Kept in a function so the view and
-- register_for_event() cannot drift apart.
create or replace function public.pending_hold_interval()
returns interval
language sql
immutable
set search_path = public, pg_temp
as $$ select interval '1 hour' $$;

revoke all on function public.pending_hold_interval() from public;
grant execute on function public.pending_hold_interval()
  to anon, authenticated, service_role;


-- ---------------------------------------------------------------------------
-- event_availability
-- ---------------------------------------------------------------------------
-- Public seat counts: an event id, its capacity, and how many seats are taken.
-- Nothing else.
--
-- The website cannot count `registrations` directly — that table holds names,
-- emails and phone numbers and is admin-only. A logged-out visitor querying it
-- gets back an empty result rather than an error, because RLS is a filter and
-- not a lock, so the count silently reads zero and every event looks empty
-- forever.
--
-- This view is how the count escapes that. It deliberately does NOT use
-- `security_invoker`: it runs with its creator's privileges, so it can read
-- registrations even though the caller cannot. That is safe here precisely
-- because it returns no row-level data — there is no column that could leak a
-- name or an email. Aggregation is the privacy boundary.
create or replace view public.event_availability as
select
  e.id               as event_id,
  e.max_participants as capacity,
  count(r.id)        as taken
from public.events e
left join public.registrations r
  on r.event_id = e.id
  -- Refunded people are not attending; their seat is free again.
  and r.payment_status <> 'refunded'
  -- A pending checkout holds its seat, but only for a bounded window.
  and (
    r.payment_status <> 'pending'
    or r.created_at > now() - public.pending_hold_interval()
  )
where e.published = true
group by e.id, e.max_participants;


-- ---------------------------------------------------------------------------
-- register_for_event()
-- ---------------------------------------------------------------------------
-- The only way a registration row is created.
--
-- It exists to close a race condition. Counting registrations and then
-- inserting, as two steps in application code, means two people submitting at
-- the same moment both count 14, both decide there is room, and both insert —
-- and you have 16 people in a room for 15. No amount of JavaScript fixes that,
-- because the gap between the count and the insert is where the bug lives.
--
-- Inside one function, both steps run in a single transaction and `FOR UPDATE`
-- on the event's row makes the second caller wait for the first. Sequential
-- rather than simultaneous. The lock is per row, so bookings for other events
-- are unaffected.
--
-- Returns JSONB: either {"success": true, "id": ...} or {"error": "..."} with a
-- message already in Romanian, ready to show the visitor.
create or replace function public.register_for_event(
  p_event_id UUID,
  p_full_name TEXT,
  p_email TEXT,
  p_phone TEXT,
  p_payment_status TEXT DEFAULT 'free'
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_max_participants INTEGER;
  v_published        BOOLEAN;
  v_current_count    INTEGER;
  v_registration_id  UUID;
BEGIN
  -- Guard against a status the caller made up. The table has a CHECK covering
  -- these too; this returns clean JSON instead of a raw constraint violation.
  IF p_payment_status NOT IN ('free', 'pending', 'completed', 'refunded') THEN
    RETURN jsonb_build_object('error', 'Invalid payment status.');
  END IF;

  SELECT max_participants, published
    INTO v_max_participants, v_published
    FROM events
   WHERE id = p_event_id
     FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('error', 'Evenimentul nu există.');
  END IF;

  -- Draft events are not bookable. The API checks this too, but a rule this
  -- important belongs next to the data as well.
  IF v_published IS NOT TRUE THEN
    RETURN jsonb_build_object('error', 'Evenimentul nu este disponibil.');
  END IF;

  -- Must match event_availability exactly. See the note above.
  SELECT COUNT(*)
    INTO v_current_count
    FROM registrations
   WHERE event_id = p_event_id
     AND payment_status <> 'refunded'
     AND (
       payment_status <> 'pending'
       OR created_at > now() - public.pending_hold_interval()
     );

  -- NULL capacity means unlimited, so the check is skipped entirely.
  IF v_max_participants IS NOT NULL AND v_current_count >= v_max_participants THEN
    RETURN jsonb_build_object('error', 'Evenimentul este complet.');
  END IF;

  INSERT INTO registrations (event_id, full_name, email, phone, payment_status)
  VALUES (p_event_id, p_full_name, p_email, p_phone, p_payment_status)
  RETURNING id INTO v_registration_id;

  RETURN jsonb_build_object('success', true, 'id', v_registration_id);
END;
$$;

-- Only the server-side key may call this. The website reaches it through
-- /api/register, which is where the CAPTCHA, the rate limiter and the input
-- validation live — letting the browser call it directly skips all three, and
-- `p_payment_status => 'completed'` would then book a paid event without paying.
--
-- `from public` is the line that does the work. Revoking anon and authenticated
-- by name is not sufficient and previously was not: both inherited EXECUTE from
-- the PUBLIC grant Postgres adds at creation time.
--
-- Asserted from the outside in tests/rpc-exposure.spec.ts, which calls the RPC
-- over HTTP with the publishable key and expects a refusal. Testing the grant
-- would prove the statement is spelled right; testing the endpoint proves the
-- door is shut.
revoke all on function public.register_for_event(UUID, TEXT, TEXT, TEXT, TEXT)
  from public;
revoke all on function public.register_for_event(UUID, TEXT, TEXT, TEXT, TEXT)
  from anon, authenticated;
grant execute on function public.register_for_event(UUID, TEXT, TEXT, TEXT, TEXT)
  to service_role;


-- ############################################################################
-- 6. GRANTS
-- ############################################################################
--
-- Postgres checks two separate things before letting a query through:
--
--   1. GRANT  -- may this role touch this table at all?
--   2. RLS    -- which rows may it touch?
--
-- Both must pass, and they fail differently: a missing grant is a hard
-- "permission denied", while RLS silently returns nothing. Two features here
-- shipped broken because the policy was written and the grant was not, so the
-- grants are declared in this file rather than clicked in the dashboard.
--
--   anon           a visitor who is not logged in (the public pages)
--   authenticated  a logged-in user (in practice: the instructor in /admin)
--   service_role   the secret server-side key used by API routes. Bypasses RLS
--                  entirely, which is why it must never reach the browser.

-- Start from nothing on everything that is not public content, so a grant
-- added by hand in the dashboard cannot survive a rebuild unnoticed.
revoke all on public.events                     from anon;
revoke all on public.blog_posts                 from anon;
revoke all on public.testimonials               from anon;
revoke all on public.registrations              from anon;
revoke all on public.contact_messages           from anon;
revoke all on public.waiting_list               from anon;
revoke all on public.waiting_list_notifications from anon;
revoke all on public.email_templates            from anon;

-- Not revoked here, and worth knowing why: Supabase's project setup runs
-- `alter default privileges in schema public grant all on tables to anon`, so
-- every table created since — whatsapp_links, site_content, faqs, profiles —
-- carries REFERENCES, TRIGGER, TRUNCATE and MAINTAIN for anon. Those are not
-- reachable through PostgREST, which only issues SELECT/INSERT/UPDATE/DELETE,
-- and no SELECT was ever granted, so the tables stay unreadable. It is the
-- default posture on every Supabase project; singling out one table would
-- diverge from production for no gain. The revokes above exist because those
-- tables previously had real grants that had to come off.

-- Visitors read published content and nothing else. Never a write: every
-- public form posts to an API route holding the service key, which is what
-- keeps the CAPTCHA and the validation mandatory.
grant select on public.events             to anon;
grant select on public.blog_posts         to anon;
grant select on public.testimonials       to anon;
grant select on public.site_content       to anon;
grant select on public.faqs               to anon;
grant select on public.event_availability to anon;

-- profiles is unused (no public sign-up) and its RLS restricts every row to
-- `auth.uid() = id`, so this grant reaches nothing. Recorded because production
-- has it and this file is meant to reproduce production exactly — revoking it
-- would be a change, not a transcription, and an unused table with a
-- self-referential policy is not where that risk is worth taking.
grant select on public.profiles to anon, authenticated;

-- Logged-in users get full CRUD at the grant level; the RLS policies above
-- still require is_admin() for every operation, so a non-admin account gets an
-- empty result rather than data.
grant select, insert, update, delete on public.events                     to authenticated;
grant select, insert, update, delete on public.blog_posts                 to authenticated;
grant select, insert, update, delete on public.testimonials               to authenticated;
grant select, insert, update, delete on public.registrations              to authenticated;
grant select, insert, update, delete on public.contact_messages           to authenticated;
grant select, insert, update, delete on public.email_templates            to authenticated;
grant select, insert, update, delete on public.waiting_list               to authenticated;
grant select, insert, update, delete on public.waiting_list_notifications to authenticated;
grant select, insert, update, delete on public.site_content               to authenticated;
grant select, insert, update, delete on public.faqs                       to authenticated;
grant select, insert, update, delete on public.whatsapp_links             to authenticated;
grant select                         on public.event_availability         to authenticated;

grant select, insert, update, delete on public.events                     to service_role;
grant select, insert, update, delete on public.blog_posts                 to service_role;
grant select, insert, update, delete on public.testimonials               to service_role;
grant select, insert, update, delete on public.registrations              to service_role;
grant select, insert, update, delete on public.contact_messages           to service_role;
grant select, insert, update, delete on public.email_templates            to service_role;
grant select, insert, update, delete on public.waiting_list               to service_role;
grant select, insert, update, delete on public.waiting_list_notifications to service_role;
grant select, insert, update, delete on public.site_content               to service_role;
grant select, insert, update, delete on public.faqs                       to service_role;
grant select, insert, update, delete on public.whatsapp_links             to service_role;

-- Every table grants to service_role, and for a while this view did not. The
-- symptom is `permission denied for view event_availability` from an API route
-- using the secret key, which reads like an RLS problem and is not one — the
-- service role bypasses RLS entirely, so the usual debugging instinct leads
-- nowhere. Safe to grant: the view exposes no personal data, and the service
-- role could already read the underlying table.
grant select on public.event_availability to service_role;


