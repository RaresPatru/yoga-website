-- ############################################################################
-- 8. STORAGE
-- ############################################################################
--
-- One public bucket, `media`, holding photographs, audio and video for the blog
-- and the site content.

insert into storage.buckets (id, name, public)
values ('media', 'media', true)
on conflict (id) do nothing;

-- Uploads go browser -> Supabase directly, using a short-lived signed URL that
-- /api/upload issues after checking the caller is an admin. That path exists
-- because Vercel caps a serverless function's request body at 4.5 MB, which is
-- smaller than most phone video.
--
-- The consequence is that the browser never passes back through our code, so a
-- check written in the API route is only a suggestion. These limits are set on
-- the bucket so Supabase enforces them itself.
update storage.buckets
set
  file_size_limit = 52428800, -- 50 MB, matching what the admin UI promises
  allowed_mime_types = array[
    'image/jpeg',
    'image/png',
    'image/gif',
    'image/webp',
    -- image/svg+xml is deliberately absent: an SVG is XML and can contain
    -- <script>, so serving one from a public bucket is a stored-XSS vector.
    'audio/mpeg',
    'audio/wav',
    'audio/ogg',
    'audio/opus',
    'audio/webm',
    'audio/mp4',
    'audio/x-m4a',
    'audio/flac',
    'audio/aac',
    'video/mp4',
    'video/webm',
    'video/quicktime',
    'video/x-msvideo'
  ]
where id = 'media';

-- Scoped to `authenticated`, which governs *listing* only. Serving is
-- unaffected: requests to /storage/v1/object/public/media/... never consult
-- RLS — that is what makes a bucket public — so anonymous visitors load images
-- normally and simply cannot enumerate the bucket. The one thing that does need
-- to list is the admin media library, which runs in the browser under the
-- instructor's own session.
drop policy if exists "Anyone can view media files" on storage.objects;
drop policy if exists "Signed-in users can list media files" on storage.objects;
create policy "Signed-in users can list media files"
  on storage.objects for select
  to authenticated
  using (bucket_id = 'media');

-- The admin media library (components/admin/media-library.tsx) lists and
-- deletes files from the browser with the logged-in user's own session, not
-- through an API route, so `authenticated` needs privileges on the storage
-- tables themselves. Without these the library comes back empty and the
-- Supabase dashboard shows the files sitting there perfectly fine.
grant select, insert, delete on storage.objects to authenticated;
grant select, insert, delete on storage.buckets to authenticated;


